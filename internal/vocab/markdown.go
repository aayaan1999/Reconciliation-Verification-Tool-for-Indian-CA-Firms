package vocab

import (
	"bytes"
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

// DocPath is where the generated vocabulary document lives, relative to the repository root.
const DocPath = "docs/fact-vocabulary.md"

// Markdown returns the human-readable vocabulary document (FV-02): document types, then
// facts grouped by document type, then record types. It is generated, never hand-edited,
// and depends only on the vocabulary's content, so the same vocabulary gives the same bytes.
func Markdown(v *Vocab) []byte {
	var b bytes.Buffer
	b.WriteString("# Fact vocabulary\n\n")
	b.WriteString("Generated from `content/vocabulary/facts.yaml` and `content/vocabulary/records.yaml` by " +
		"`go run ./cmd/recon-dev vocab-doc`. Do not edit this file by hand.\n\n")
	b.WriteString("Format profiles may only write these names, and rules may only read them (FV-03). " +
		"A name is never reused with a different meaning.\n\n")
	fmt.Fprintf(&b, "Vocabulary version: %d\n\n", v.version)
	fmt.Fprintf(&b, "Content hash: `%s`\n\n", v.hash)

	b.WriteString("## Document types\n\n")
	b.WriteString("| Document type | Fact names start with | Description | Since version |\n|---|---|---|---|\n")
	for _, d := range v.docTypes {
		fmt.Fprintf(&b, "| `%s` | `%s.` | %s | %d |\n", d.Name, d.Prefix, cell(d.Description), d.SinceVocab)
	}

	b.WriteString("\n## Facts by document type\n")
	for _, d := range v.docTypes {
		fmt.Fprintf(&b, "\n### `%s`: %s\n\n", d.Name, cell(d.Description))
		var rows []Fact
		for _, f := range v.facts {
			if f.DocumentType == d.Name {
				rows = append(rows, f)
			}
		}
		if len(rows) == 0 {
			b.WriteString("No facts yet.\n")
			continue
		}
		b.WriteString("| Fact name | Kind | Periodicity | Description | Since version | Retired in version |\n|---|---|---|---|---|---|\n")
		for _, f := range rows {
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %d | %s |\n",
				f.Name, f.Kind, f.Periodicity, cell(f.Description), f.SinceVocab, retired(f.DeprecatedIn))
		}
	}

	b.WriteString("\n## Record types\n\n")
	if len(v.recordTypes) == 0 {
		b.WriteString("No record types yet.\n")
	} else {
		b.WriteString("| Record type | Match key | Amounts | Other fields | Description | Since version | Retired in version |\n|---|---|---|---|---|---|---|\n")
		for _, r := range v.recordTypes {
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %d | %s |\n",
				r.Name, names(r.MatchKey), names(r.Amounts), names(r.Fields), cell(r.Description), r.SinceVocab, retired(r.DeprecatedIn))
		}
	}
	return b.Bytes()
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func names(list []string) string {
	if len(list) == 0 {
		return "none"
	}
	return "`" + strings.Join(list, "`, `") + "`"
}

func retired(v int) string {
	if v == 0 {
		return ""
	}
	return strconv.Itoa(v)
}

var (
	docVersion = regexp.MustCompile(`(?m)^Vocabulary version: (\d+)$`)
	docHash    = regexp.MustCompile("(?m)^Content hash: `([0-9a-f]{64})`$")
)

// CheckDoc compares a committed vocabulary document with the one v generates. It returns
// nil when they match (line endings aside). When the content changed but the version did
// not, it says to increase vocab_version; otherwise it says to regenerate the document.
func CheckDoc(committed []byte, v *Vocab) error {
	committed = bytes.ReplaceAll(committed, []byte("\r\n"), []byte("\n"))
	if bytes.Equal(committed, Markdown(v)) {
		return nil
	}
	if err := CheckVersionBumped(committed, v); err != nil {
		return err
	}
	return fmt.Errorf("%s is out of date; regenerate it with: go run ./cmd/recon-dev vocab-doc", DocPath)
}

// CheckVersionBumped refuses a vocabulary whose content differs from the committed
// document's while its version is the same or lower: every change must increase
// vocab_version (§A10). A missing or unreadable header is not an error here.
func CheckVersionBumped(committed []byte, v *Vocab) error {
	vm, hm := docVersion.FindSubmatch(committed), docHash.FindSubmatch(committed)
	if vm == nil || hm == nil || string(hm[1]) == v.hash {
		return nil
	}
	old, _ := strconv.Atoi(string(vm[1]))
	if v.version <= old {
		return fmt.Errorf("the vocabulary changed but vocab_version is still %d (the document was generated from version %d); "+
			"increase vocab_version in both %s and %s", v.version, old, FactsFile, RecordsFile)
	}
	return nil
}
